function checkLogin(string $username): string
{
    if (is_numeric($username)) {
        return 'error';
    }

    // Р вЂ”Р В°Р С—РЎР‚Р ВµРЎвЂ°РЎвЂР Р…Р Р…РЎвЂ№Р Вµ Р С—Р В°РЎР‚РЎвЂ№ Р С—Р С•Р Т‘РЎР‚РЎРЏР Т‘
    if (preg_match('/--|__|==|@@|::/', $username)) {
        return 'error';
    }

    // Р СћРЎР‚Р С‘ Р В±РЎС“Р С”Р Р†РЎвЂ№ Р С—Р С•Р Т‘РЎР‚РЎРЏР Т‘
    if (preg_match('/([a-zA-Z])\1{2}/i', $username)) {
        return 'error';
    }

    // Р СћРЎР‚Р С‘ РЎвЂ Р С‘РЎвЂћРЎР‚РЎвЂ№ Р С—Р С•Р Т‘РЎР‚РЎРЏР Т‘
    if (preg_match('/(\d)\1{2}/', $username)) {
        return 'error';
    }

    // Р СџР С•Р Т‘РЎРѓРЎвЂЎРЎвЂРЎвЂљ РЎРѓР С—Р ВµРЎвЂ РЎРѓР С‘Р СР Р†Р С•Р В»Р С•Р Р†: Р Р…Р Вµ Р В±Р С•Р В»Р ВµР Вµ 2 Р С”Р В°Р В¶Р Т‘Р С•Р С–Р С• Р С‘ РЎРѓРЎС“Р СР СР В°РЎР‚Р Р…Р С• Р Р…Р Вµ Р В±Р С•Р В»Р ВµР Вµ 4
    $specials = ['-', '_', '=', '@', ':'];
    $specTotal = 0;
    foreach ($specials as $ch) {
        $cnt = substr_count($username, $ch);
        if ($cnt > 2) {
            return 'error';
        }
        $specTotal += $cnt;
    }
    if ($specTotal > 4) {
        return 'error';
    }

    // Р СџР С•Р Т‘РЎРѓРЎвЂЎРЎвЂРЎвЂљ Р Р†РЎвЂ¦Р С•Р В¶Р Т‘Р ВµР Р…Р С‘Р в„– Р С”Р В°Р В¶Р Т‘Р С•Р в„– Р В±РЎС“Р С”Р Р†РЎвЂ№: Р Р…Р Вµ Р В±Р С•Р В»Р ВµР Вµ 3
